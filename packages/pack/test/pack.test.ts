describe('rendering', () => {
  it('embeds the spec safely: a spec containing a closing script tag cannot break out of the page', () => {
    const evil = { ...spec, intro: '</script><script>alert(1)</script>' };
    const html = artefactHtml('doc', evil);
    expect(embedSpec(evil)).not.toContain('<');
    expect(html).not.toContain('</script><script>alert');
  });
  it('passes the selected theme and a validated brand colour into the HTML', () => {
    expect(artefactHtml('explainer', spec, 'dark')).toContain('<html lang="en" data-theme="dark">');
    expect(artefactHtml('prototype', { ...spec, brand: 'red;}</style><script>x' })).not.toContain('</style><script>x');
    for (const k of ['doc', 'explainer', 'prototype'] as const) { const h = artefactHtml(k, spec); expect(h).not.toContain('__SPEC__'); expect(h).not.toContain('__BRAND__'); }
  });
  it('the viewer iframe sandbox grants scripts but not same-origin', () => {
    expect(PACK_IFRAME_SANDBOX).toBe('allow-scripts');
    expect(PACK_IFRAME_SANDBOX).not.toContain('same-origin');
  });
});

describe('wording refinement cannot change facts', () => {
  const good = () => ({ steps: spec.steps.map((s: any) => ({ n: +s.n, title: `Nice ${s.title}`, say: 'Plain words.', rules: s.rules.map(([t, x]: [string, string]) => [t, x.replace(/^([A-Z]+-[A-Z]+-\d+): /, '$1: Friendly ')]), chips: s.chips.map(([k, x]: [string, string]) => [k, x.toLowerCase()]) })) });
  it('accepts pure rewording', () => {
    const r = sanitizeRefinement(spec, good());
    expect(r.rejected).toEqual([]);
    expect(r.steps).toHaveLength(7);
  });
  it('rejects refined rules that drop or invent rule/incident ids, or change the number of rules', () => {
    const bad: any = good();
    bad.steps[4].rules = bad.steps[4].rules.map(([t, x]: [string, string]) => [t, x.replace('NB-COLLECTION-002', 'NB-MADE-UP-999')]);
    bad.steps[5].rules.pop();
    const r = sanitizeRefinement(spec, bad);
    expect(r.steps.find((s) => s.n === 5)!.rules).toBeUndefined();
    expect(r.steps.find((s) => s.n === 6)!.rules).toBeUndefined();
    expect(r.rejected.length).toBe(2);
  });
  it('rejects chips with changed keys and steps that do not exist', () => {
    const bad: any = good();
    bad.steps[0].chips[0][0] = 'other';
    bad.steps.push({ n: 99, title: 'x' });
    const r = sanitizeRefinement(spec, bad);
    expect(r.steps.find((s) => s.n === 1)!.chips).toBeUndefined();
    expect(r.rejected.some((x) => x.includes('99'))).toBe(true);
  });
  it('an applied override changes wording only: the fact hash, screens, trace and history are unchanged', () => {
    const before = specHash(spec);
    const refined = buildSpec(g, 0, { ...opt, generatedAt: spec.generated, override: { steps: sanitizeRefinement(spec, good()).steps } });
    expect(refined.refined).toBe(true);
    expect(refined.steps[0].title).toMatch(/^Nice /);
    expect(specHash(refined)).toBe(before);
    for (let i = 0; i < 7; i++) for (const k of ['screen', 'trace', 'history', 'n', 'ph']) expect(refined.steps[i][k]).toEqual(spec.steps[i][k]);
    expect(refined.sample).toEqual(spec.sample);
  });
  it('a factual change in the code changes the fact hash (so stale overrides are detectable)', () => {
    const g2: PGraph = structuredClone(g);
    g2.commits.pop(); g2.processes[0]!.stages[0]!.tables = [];
    expect(specHash(buildSpec(g2, 0, { ...opt, generatedAt: spec.generated }))).not.toBe(specHash(spec));
  });
  it('refineWording makes one tool-less call, fences the facts, and sanitises the reply', async () => {
    let seen: any; let calls = 0;
    const model: ModelClient = { provider: 't', model: 't', async complete(r) { calls++; seen = r; return { content: [{ type: 'text', text: JSON.stringify(good()) }], stopReason: 'end_turn', usage: { inputTokens: 5, outputTokens: 6 } }; } };
    const out = await refineWording(spec, Object.fromEntries(Object.values(g.requirements).map((r) => [r.id, r.body])), model);
    expect(calls).toBe(1);
    expect(seen.tools).toBeUndefined();
    expect(seen.messages[0].content).toMatch(/<untrusted-[0-9a-f]+/);
    expect(out.refinement.steps).toHaveLength(7);
  });
});

describe('spec cache', () => {
  it('is keyed by process + snapshot SHA and regenerates after a new snapshot', () => {
    const c = new SpecCache();
    const a = c.get(g, 0, 'sha1', { ...opt, generatedAt: 'x' }), b = c.get(g, 0, 'sha1', { ...opt, generatedAt: 'y' });
    expect(b).toBe(a);
    expect(c.get(g, 0, 'sha2', { ...opt, generatedAt: 'z' })).not.toBe(a);
    expect(c.size).toBe(2);
  });
});
