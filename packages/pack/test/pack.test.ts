import fs from 'node:fs';
import path from 'node:path';
import { describe, it, expect, beforeAll } from 'vitest';
import { loadFixture } from '../../../test/helpers/fixture';
import type { ModelClient } from '@lens/ai';
import { toPackGraph, buildSpec, sandboxConfig, toYaml, docMarkdown, artefactHtml, embedSpec, sanitizeRefinement, specHash, refineWording, SpecCache, PACK_IFRAME_SANDBOX, type PGraph } from '../src';

let g: PGraph; let spec: any; let cfg: any; let ref: any;
const opt = { source: 'BafozAIChallenge-project', vertical: 'Personal Insurance' };

beforeAll(async () => {
  const fx = await loadFixture();
  g = toPackGraph({
    graph: fx.graph, view: fx.view, files: fx.source, commits: fx.commits,
    tickets: fx.tickets.map((t) => ({ key: t.key, commit: t.commit })),
    incidents: fx.incidents.map((n) => ({ key: n.key, title: n.title, status: n.status, severity: n.severity, rootCause: n.rootCause, files: n.resolved.map((r) => r.resolved ?? r.input), reqs: n.reqs })),
  });
  ref = JSON.parse(fs.readFileSync(path.resolve(__dirname, '../../../test/fixtures/prototype-pack-reference.json'), 'utf8'));
  spec = buildSpec(g, 0, { ...opt, generatedAt: ref.spec.generated });
  cfg = sandboxConfig(g, 0, spec, opt);
});

describe("parity with the prototype (reference generated by the prototype's own code on the same repository)", () => {
  it('process spec is identical', () => expect(spec).toEqual(ref.spec));
  it('sandbox config, YAML and Markdown are identical', () => {
    expect(cfg).toEqual(ref.cfg);
    expect(toYaml(cfg)).toBe(ref.yaml);
    expect(docMarkdown(spec)).toBe(ref.md);
  });
});

describe('process spec facts (M10)', () => {
  it('covers the 7 New Business steps in four phases', () => {
    expect(spec.steps).toHaveLength(7);
    expect(spec.phases).toEqual(['Start', 'Capture', 'Check', 'Complete']);
  });
  it('NB-COLLECTION-002 rejects day 31 for monthly debit orders and accepts day 25', () => {
    const check = spec.steps[5].screen.checks.find((c: any) => c.code === 'NB-COLLECTION-002');
    const range = check.conds[0].ranges.find((r: any) => r.when?.vals.includes('DEBIT_ORDER'));
    expect([range.min, range.max]).toEqual([1, 28]);
    expect(31 >= range.min && 31 <= range.max).toBe(false);
    expect(25 >= range.min && 25 <= range.max).toBe(true);
  });
  it('activation is gated to SUPERVISOR or ADMIN and needs a passed validation', () => {
    const a = spec.steps[6].screen.action;
    expect(a.roles).toEqual(['SUPERVISOR', 'ADMIN']);
    expect(a.needsValidation).toBe(true);
    expect([a.from, a.to]).toEqual(['NEW', 'IN-FORCE']);
  });
  it('sample data is synthetic and the incident shows up as an open question', () => {
    expect(JSON.stringify(spec.sample)).toContain('Sizwe');
    expect(spec.openQuestions.some((q: string) => q.startsWith('INC-2291'))).toBe(true);
  });
  it('choices come from seed data and STATIC PROPERTY ... INITIAL; ID prefixes from SUBSTITUTE', () => {
    expect(spec.steps[3].screen.list.options.length).toBeGreaterThan(1);
    expect(spec.sample['Contract.ContractId']).toBe('CON-000001');
    const method = spec.steps.flatMap((s: any) => s.screen.fields ?? []).find((d: any) => d.k === 'CollectionInstruction.CollectionMethod');
    expect(method.options.map((o: any) => o.v)).toEqual(expect.arrayContaining(['DEBIT_ORDER', 'PAYROLL']));
  });
});

