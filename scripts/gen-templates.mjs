// Embeds packages/pack/templates/*.html as a TS module so the templates ship inside bundles (Next.js, worker).
import fs from 'node:fs';
const dir = 'packages/pack/templates';
const out = ['// GENERATED by scripts/gen-templates.mjs from packages/pack/templates. Do not edit.', 'export const TEMPLATES = {'];
for (const k of ['doc', 'explainer', 'prototype']) out.push(`  ${k}: ${JSON.stringify(fs.readFileSync(`${dir}/${k}.html`, 'utf8'))},`);
out.push('} as const;', 'export type PackKind = keyof typeof TEMPLATES;', '');
fs.writeFileSync('packages/pack/src/templates.ts', out.join('\n'));
console.log('templates.ts written');
